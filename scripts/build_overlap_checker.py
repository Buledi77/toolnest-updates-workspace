def load_json(path):
    with open(path) as f:
        return json.load(f)


def build_comparison_map():
    """Build a map of tool pairs to comparison URLs."""
    comparisons = {}
    if not COMPARE_DIR.exists():
        return comparisons
    for f_name in os.listdir(COMPARE_DIR):
        if f_name.endswith(".html"):
            stem = f_name.replace(".html", "")
            m = re.match(r"^(.+)-vs-(.+)$", stem)
            if m:
                a, b = m.group(1), m.group(2)
                comparisons[f"{a}|{b}"] = f"/compare/{stem}.html"
                comparisons[f"{b}|{a}"] = f"/compare/{stem}.html"
    return comparisons


def build_inline_data():
    """Build compact inline JSON for the page."""
    data = load_json(OVERLAP_DATA)
    comparisons = build_comparison_map()

    compact = {
        "tools": {},
        "categories": data["categories"],
        "alternatives": data["alternatives"],
        "shared_jobs": data["shared_jobs"],
        "comparisons": comparisons,
    }

    for tid, tool in data["tools"].items():
        compact["tools"][tid] = {
            "name": tool["name"],
            "cat": tool["category"],
            "best": tool["best_for"],
            "pros": tool["pros"],
            "logo": tool["logo"],
            "site": tool["site"],
        }

    return compact, data


